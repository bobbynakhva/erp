/* Disposable PostgreSQL-backed owner/customer deployments for integration
 * tests. No existing users, business records or application credentials used. */
const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { pool } = require("../db");
const { initOnboarding } = require("../onboarding-engine");
const { initPlatform } = require("../platform/schema");
const { createPlatformController } = require("../platform/controller");
const { CustomerDeployment } = require("../platform/customer-deployment");
const { randomToken, hashPassword } = require("../platform/security");

async function isolatedDatabase() {
  const schema = `platform_test_${crypto.randomBytes(8).toString("hex")}`;
  await pool.query(`CREATE SCHEMA ${schema}`);
  const database = {
    schema,
    async connect() {
      const client = await pool.connect();
      await client.query(`SET search_path TO ${schema},pg_catalog`);
      // Discard scoped connections rather than return search_path to a live pool.
      return { query: (...args) => client.query(...args), release: () => client.release(true) };
    },
    async query(...args) {
      const client = await database.connect();
      try { return await client.query(...args); } finally { client.release(); }
    },
    async close() { await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); }
  };
  return database;
}
function sendJson(res, status, body) {
  res.writeHead(status, { "Content-Type": "application/json", "Cache-Control": "no-store" });
  res.end(JSON.stringify(body));
}
async function readBody(req) {
  let value = "";
  for await (const chunk of req) value += chunk;
  return JSON.parse(value || "{}");
}
const assets = path.join(__dirname, "../public/platform");
function staticPage(req, res, invite = false) {
  const url = new URL(req.url, "http://fixture.invalid");
  const file = ["/", "/owner", "/accept-invite"].includes(url.pathname) ?
    (invite ? "invite.html" : "owner.html") : path.basename(url.pathname);
  if (!["owner.html", "owner.css", "owner.js", "invite.html", "invite.js"].includes(file)) {
    res.writeHead(404); return res.end();
  }
  res.writeHead(200, { "Content-Type": file.endsWith(".html") ? "text/html" : file.endsWith(".js") ? "text/javascript" : "text/css" });
  res.end(fs.readFileSync(path.join(assets, file)));
}
async function startServer(handler) {
  const server = http.createServer(handler);
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  return {
    server, url: `http://127.0.0.1:${server.address().port}`,
    close: () => new Promise(resolve => {
      server.close(resolve);
      server.closeAllConnections();
    })
  };
}
async function createOwnerFixture() {
  const database = await isolatedDatabase();
  await initPlatform(database);
  const bootstrapKey = randomToken();
  let controller;
  const web = await startServer((req, res) => {
    const url = new URL(req.url, "http://fixture.invalid");
    if (url.pathname.startsWith("/api/")) return controller(req, res, url);
    staticPage(req, res);
  });
  controller = createPlatformController({
    pool: database, readBody, sendJson, bootstrapKey, publicUrl: web.url,
    secureCookies: false, allowHttp: true
  });
  return {
    ...web, database, bootstrapKey,
    async close() { await web.close(); await database.close(); }
  };
}
async function createCustomerFixture({ controlUrl, companyId, deploymentKey, configuredUrl }) {
  const database = await isolatedDatabase();
  await database.query(`
    CREATE TABLE factories(id integer PRIMARY KEY,name text,gstin text,state_code text,state_name text);
    CREATE TABLE financial_years(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,factory_id integer,min_year integer,max_year integer,is_current boolean);
    CREATE TABLE users(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,factory_id integer,year_label text,user_code integer,username text,password_stored text,role_key text,role_name text,
      UNIQUE(factory_id,year_label,user_code),UNIQUE(factory_id,year_label,username));
    CREATE TABLE misc(factory_id integer,year_label text,print_head text,print_short_addr text,my_pan_no text,
      prefix_quote text,prefix_po text,prefix_wo text,prefix_enq text,book_type smallint,book_type_inv smallint,
      PRIMARY KEY(factory_id,year_label));
    CREATE TABLE user_rights(factory_id integer,year_label text,user_code integer,PRIMARY KEY(factory_id,year_label,user_code));
    CREATE TABLE user_right_values(factory_id integer,year_label text,user_code integer,ctrl_key text,level integer,
      PRIMARY KEY(factory_id,year_label,user_code,ctrl_key));
    CREATE TABLE view_rights(factory_id integer,year_label text,sl_no integer,frm_name text,topic text,sub_topic text,ctrl_key text,
      PRIMARY KEY(factory_id,year_label,sl_no));
    INSERT INTO factories VALUES(1,'Bootstrap placeholder','','','');
    INSERT INTO financial_years(factory_id,min_year,max_year,is_current) VALUES(1,2026,2027,true);
  `);
  await database.query("INSERT INTO users(factory_id,year_label,user_code,username,password_stored) VALUES(1,'2026-27',1,'SAMPLE',$1)", [await hashPassword(randomToken())]);
  await initOnboarding(database, { newFactoryId: 1, yearLabel: "2026-27" });
  let runtime;
  const web = await startServer((req, res) => {
    const url = new URL(req.url, "http://fixture.invalid");
    if (url.pathname.startsWith("/api/deployment/")) return runtime.handle(req, res, url, { readBody, sendJson });
    if (url.pathname === "/api/erp-probe") {
      try { runtime.assertAccess(); return sendJson(res, 200, { ok: true }); }
      catch (e) { return sendJson(res, e.status, { error: e.message }); }
    }
    staticPage(req, res, true);
  });
  runtime = new CustomerDeployment({
    pool: database, controlUrl, companyId, deploymentKey,
    deploymentUrl: configuredUrl || web.url, allowHttp: true
  });
  return {
    ...web, database, runtime,
    async start() { await runtime.init({ newFactoryId: 1, yearLabel: "2026-27" }); },
    async close() { runtime.stop(); await web.close(); await database.close(); }
  };
}
