function encrypDecryp(value) {
  let out = "";
  const text = String(value ?? "");
  for (let i = 0; i < text.length; i += 1) {
    const code = text.charCodeAt(i) & 0xff;
    out += String.fromCharCode((code + 0x80) % 0x100);
  }
  return out;
}

function yearLabel(minYear, maxYear) {
  return String(minYear) + "-" + String(maxYear).slice(-2);
}

