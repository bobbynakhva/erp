async function scopeUsersToYears() {
  const loose = await pool.query(
    "SELECT id, factory_id, username, password_stored FROM users WHERE year_label IS NULL ORDER BY id"
  );
  for (const user of loose.rows) {
    const years = await pool.query(
      "SELECT min_year, max_year, is_current FROM financial_years WHERE factory_id = $1 ORDER BY min_year",
      [user.factory_id]
    );
    if (years.rowCount === 0) continue;
    const maxCode = await pool.query(
      "SELECT COALESCE(MAX(user_code), 0) AS n FROM users WHERE factory_id = $1",
      [user.factory_id]
    );
    const code = Number(maxCode.rows[0].n) + 1;
    const current = years.rows.find((row) => row.is_current) || years.rows[years.rows.length - 1];
    const currentLabel = yearLabel(current.min_year, current.max_year);
    await pool.query(
      "UPDATE users SET year_label = $1, user_code = $2 WHERE id = $3",
      [currentLabel, code, user.id]
    );
    for (const row of years.rows) {
      const label = yearLabel(row.min_year, row.max_year);
      if (label === currentLabel) continue;
      await pool.query(
        `INSERT INTO users (factory_id, username, password_stored, year_label, user_code)
         VALUES ($1, $2, $3, $4, $5)`,
        [user.factory_id, user.username, user.password_stored, label, code]
      );
    }
  }
}

