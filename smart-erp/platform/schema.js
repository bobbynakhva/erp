async function initPlatform(pool) {
  const customerTable = await pool.query("SELECT to_regclass('customer_deployment_binding') AS binding");
  if (customerTable.rows[0].binding &&
      (await pool.query("SELECT 1 FROM customer_deployment_binding LIMIT 1")).rowCount) {
    throw new Error("This is a bound customer database. The owner control plane must use a different database.");
  }
  await pool.query(`
    CREATE TABLE IF NOT EXISTS platform_owners (
      id uuid PRIMARY KEY, email text NOT NULL UNIQUE, password_hash text NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS platform_sessions (
      token_hash text PRIMARY KEY, owner_id uuid NOT NULL REFERENCES platform_owners(id),
      created_at timestamptz NOT NULL DEFAULT now(), last_seen_at timestamptz NOT NULL DEFAULT now(),
      expires_at timestamptz NOT NULL
    );
    CREATE TABLE IF NOT EXISTS platform_login_limits (
      key_hash text PRIMARY KEY, attempts integer NOT NULL, window_start timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS platform_companies (
      id uuid PRIMARY KEY, name text NOT NULL, slug text NOT NULL UNIQUE,
      admin_email text NOT NULL, year_start integer NOT NULL, plan text NOT NULL,
      trial_ends_on date, deployment_url text UNIQUE, deployment_key_hash text UNIQUE,
      instance_id uuid UNIQUE, access_status text NOT NULL DEFAULT 'active'
        CHECK(access_status IN ('active','suspended')),
      last_seen_at timestamptz, administrator_ready boolean NOT NULL DEFAULT false,
      onboarding_completed boolean NOT NULL DEFAULT false,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS platform_invitations (
      id uuid PRIMARY KEY, company_id uuid NOT NULL REFERENCES platform_companies(id),
      email text NOT NULL, token_hash text NOT NULL UNIQUE, expires_at timestamptz NOT NULL,
      claimed_instance_id uuid, accepted_at timestamptz, revoked_at timestamptz,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE IF NOT EXISTS platform_events (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      company_id uuid REFERENCES platform_companies(id), actor text NOT NULL,
      action text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
    );
  `);
}
module.exports = { initPlatform };
